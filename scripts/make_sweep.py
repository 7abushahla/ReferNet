#!/usr/bin/env python3
"""
Generate sbatch scripts for a training sweep on the AWS SLURM cluster.

Adapted from the qcfs-speck repository (scripts/make_sweep.py). A sweep is a grid,
protocol x arch x fusion x reference x init x seed, and hand-written launchers
are how arms end up silently differing in a flag. Every launcher is generated from one
template and its filename encodes the configuration. Edit this generator, never a
generated file.

  # Protocol A (anchor): control and the two reference arms on the paper's 10 folds, one GPU per arm
  python scripts/make_sweep.py --protocols A --archs changerex_r18 --fusions single --references median \
      --inits levir --seeds 42 --folds 0-9 --time 6:00:00 --name A-anchor-control
  python scripts/make_sweep.py --protocols A --archs changerex_r18 --fusions difference --references median,specimen \
      --inits levir --seeds 42 --folds 0-9 --time 6:00:00 --name A-anchor-ref

Nothing is submitted from here. Scripts are written under sweeps/<name>/ with a
submit_all.sh beside them; inspect, then queue from the repository root:

  bash sweeps/<name>/submit_all.sh

Each arm runs `python -m refer_or_clear.train` once and writes results/runs/<tag>/metrics.json.
An arm whose metrics.json already exists is skipped, so a job resubmitted after a crash or a
walltime kill reruns only the unfinished arms. A failing arm does not abort the arms after it;
the job reports every arm and exits nonzero if any failed.
"""
from __future__ import annotations

import argparse
import itertools
import re
import stat
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CLUSTER = dict(account="acc-mialhajri", partition="gpu", conda_sh="/opt/miniconda/etc/profile.d/conda.sh")
CHOICES = dict(
    protocols=("A", "B", "C", "D"),
    archs=("siamese_r18", "changerex_r18"),
    fusions=("single", "single_noex", "stacked", "difference", "attention", "attention_single"),
    references=("median", "specimen", "single"),
    inits=("imagenet", "scratch", "levir"),
)
CONFIG = {"A": "configs/protocol_a.yaml", "B": "configs/protocol_b.yaml", "C": "configs/protocol_c.yaml",
          "D": "configs/protocol_d.yaml"}
SHORT_ARCH = {"siamese_r18": "r18", "changerex_r18": "cex"}


@dataclass(frozen=True)
class Arm:
    protocol: str
    arch: str
    fusion: str
    reference: str
    init: str
    seed: int
    fold: int | None = None

    @property
    def tag(self) -> str:
        f = f"-f{self.fold}" if self.fold is not None else ""
        return f"{self.protocol}-{SHORT_ARCH[self.arch]}-{self.fusion}-{self.reference}-{self.init}{f}-s{self.seed}"


def expand_arms(protocols, archs, fusions, references, inits, seeds, folds=(None,)) -> list[Arm]:
    """The grid with seeds innermost, then folds, so a job cut short leaves whole cells."""
    for name, values in dict(protocols=protocols, archs=archs, fusions=fusions,
                             references=references, inits=inits).items():
        bad = [v for v in values if v not in CHOICES[name]]
        if bad:
            raise ValueError(f"unknown {name} {bad}; expected one of {CHOICES[name]}")
    return [Arm(p, b, f, r, t, int(s), k)
            for p, b, f, r, t, k, s in itertools.product(protocols, archs, fusions, references, inits, folds, seeds)]


def parse_folds(s: str) -> list:
    """'' -> [None]; '0-9' -> [0..9]; '2,5' -> [2, 5]."""
    s = s.strip()
    if not s:
        return [None]
    if "-" in s:
        lo, hi = (int(x) for x in s.split("-"))
        return list(range(lo, hi + 1))
    return [int(x) for x in _csv(s)]


def pack_jobs(arms: list[Arm], group_size: int) -> list[list[Arm]]:
    return [arms[i:i + group_size] for i in range(0, len(arms), group_size)]


PREAMBLE = """#!/bin/bash
#SBATCH --account={account}
#SBATCH --partition={partition}
#SBATCH --nodes=1
#SBATCH --ntasks=1
#SBATCH --gres=gpu:1
#SBATCH --cpus-per-task={cpus}
#SBATCH --mem={mem}
#SBATCH --time={time}
#SBATCH --job-name={job_name}
#SBATCH --output=logs/slurm/%x-%j.out
#
# {n} arm(s), run back to back on ONE GPU in this order:
{arm_list}
#
# Generated by scripts/make_sweep.py. Edit the generator, not this file, or the
# arms of the sweep drift apart. Submit from the repository root.

set -u

ENV="{env}"
source "{conda_sh}"
conda activate "$ENV"
[[ "$CONDA_PREFIX" == "$ENV" || "$(basename "$CONDA_PREFIX")" == "$ENV" ]] || {{
    echo "[NO] conda env '$ENV' not active (CONDA_PREFIX=$CONDA_PREFIX)"; exit 1; }}

if [[ -n "${{SLURM_SUBMIT_DIR:-}}" ]]; then cd "$SLURM_SUBMIT_DIR"
else cd "$(cd "$(dirname "${{BASH_SOURCE[0]}}")/../.." && pwd)"; fi

[[ -f pyproject.toml && -d src/refer_or_clear ]] || {{
    echo "[FATAL] not at the repo root: $PWD"
    echo "        submit from the repo root, e.g.  sbatch sweeps/<name>/<job>.sh"
    exit 1
}}

REPO_ROOT="$PWD"
ENV_PY="$CONDA_PREFIX/bin/python"
export PYTHONPATH="$REPO_ROOT/src${{PYTHONPATH:+:$PYTHONPATH}}"
export CUBLAS_WORKSPACE_CONFIG=:4096:8
export PYTHONUNBUFFERED=1
# TMPDIR defaults to the node's root EBS volume (11.7 MB/s); use node-local NVMe.
export TMPDIR="/scratch/$USER/tmp"
mkdir -p "$TMPDIR"

# The processed pairs are thousands of 512 x 800 images read every epoch: /shared (NFS, ~100 MB/s)
# would be the bottleneck, so stage them once per job to node-local /scratch (~2.4 GB/s).
[[ -n "$(ls data/processed/splits/*.csv 2>/dev/null)" ]] || {{
    echo "[FATAL] data/processed missing; run scripts/cluster/stage-data.sh on the login node"; exit 1; }}
export ROC_DATA="/scratch/$USER/roc-data"
mkdir -p "$ROC_DATA"
rsync -a --delete data/processed/ "$ROC_DATA/" || {{ echo "[FATAL] staging to /scratch failed"; exit 1; }}
echo "[ok] data staged to $ROC_DATA ($(du -sh "$ROC_DATA" | cut -f1))"

# A real cuDNN convolution, not an import: an env that is wrong for this node imports fine and dies hours in.
"$ENV_PY" -c "
import torch, torch.nn as nn
assert torch.cuda.is_available(), 'CUDA not available'
nn.Conv2d(3, 16, 3, padding=1).cuda()(torch.randn(2, 3, 64, 64, device='cuda'))
torch.cuda.synchronize()
print(f'[ok] {{torch.cuda.get_device_name(0)}} | torch {{torch.__version__}} | cuda {{torch.version.cuda}}')
" || {{ echo "[FATAL] broken env or no GPU on $(hostname)"; exit 1; }}
echo "[ok] repo $(git rev-parse --short HEAD 2>/dev/null || echo '?') on $(hostname), CUDA_VISIBLE_DEVICES=${{CUDA_VISIBLE_DEVICES:-unset}}"

DONE=()
SKIPPED=()
FAILED=()
"""

ARM = """
# ---------------------------------------------------------------- arm {index}/{total}
RUN_DIR="results/runs/{tag}"
if [[ -f "$RUN_DIR/metrics.json" ]]; then
    echo "[skip] {tag}: $RUN_DIR/metrics.json exists"; SKIPPED+=("{tag}")
else
    echo "[run] {tag} at $(date '+%F %T')"
    if "$ENV_PY" -u -m refer_or_clear.train \\
        --config {config} \\
        --arch {arch} \\
        --fusion {fusion} \\
        --reference {reference} \\
        --init {init} \\
        --seed {seed} \\{fold_flag}
        --data-root "$ROC_DATA" \\
        --run-dir "$RUN_DIR"{optional}; then
        DONE+=("{tag}")
    else
        echo "[FAIL] {tag}"; FAILED+=("{tag}")
    fi
fi
"""

FOOTER = """
# ------------------------------------------------------------------- summary
echo
echo "==================== $(date '+%F %T') ===================="
echo "  done    : ${DONE[*]:-(none)}"
echo "  skipped : ${SKIPPED[*]:-(none)}"
echo "  FAILED  : ${FAILED[*]:-(none)}"
echo "=========================================================="
[[ ${#FAILED[@]} -eq 0 ]] || exit 1
echo "Done."
"""

SUBMIT = """#!/bin/bash
# Generated by scripts/make_sweep.py. Submits the {n} job(s) of sweep '{name}'.
# Every job cd's to SLURM_SUBMIT_DIR, which is wherever THIS script runs, so run it from the repo root.
set -u
[[ -f pyproject.toml && -d src/refer_or_clear ]] || {{
    echo "[FATAL] not at the repo root: $PWD"; echo "        run  bash {out}/submit_all.sh  from the repo root"; exit 1; }}
mkdir -p logs/slurm
"""


def render_job(arms, *, job_name, time, mem, cpus, env, extra, suffix="") -> str:
    optional = f" \\\n        {extra}" if extra else ""
    text = PREAMBLE.format(n=len(arms), arm_list="\n".join(f"#   {i}. {a.tag}" for i, a in enumerate(arms, 1)),
                           job_name=job_name, time=time, mem=mem, cpus=cpus, env=env, **CLUSTER)
    for i, a in enumerate(arms, 1):
        text += ARM.format(index=i, total=len(arms), tag=a.tag + suffix, config=CONFIG[a.protocol], arch=a.arch,
                           fusion=a.fusion, reference=a.reference, init=a.init, seed=a.seed,
                           fold_flag="" if a.fold is None else f"\n        --fold {a.fold} \\",
                           optional=optional)
    return text + FOOTER


def _csv(s: str) -> list[str]:
    return [x.strip() for x in s.split(",") if x.strip()]


def parse_args(argv=None):
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--protocols", default="A", help=f"comma list from {CHOICES['protocols']}")
    p.add_argument("--archs", default="siamese_r18", help=f"comma list from {CHOICES['archs']}")
    p.add_argument("--fusions", default="single,stacked,difference,attention", help=f"comma list from {CHOICES['fusions']}")
    p.add_argument("--references", default="median", help=f"comma list from {CHOICES['references']}")
    p.add_argument("--inits", default="imagenet", help=f"comma list from {CHOICES['inits']}")
    p.add_argument("--seeds", default="42,43,44", help="comma list of seeds")
    p.add_argument("--folds", default="", help="fold or group indices, e.g. 0-9 or 2,5 (Protocols A and B); empty for none")
    p.add_argument("--name", default="sweep", help="sweep name: output folder and job-name prefix")
    p.add_argument("--out", default=None, help="output folder (default sweeps/<name>)")
    p.add_argument("--group-size", type=int, default=1,
                   help="arms run back to back per job; 1 (default) runs every arm on its own GPU")
    p.add_argument("--extra", default="", help="extra flags passed verbatim to every train call")
    p.add_argument("--suffix", default="", help="appended to every run tag (e.g. -smoke), so pilot and smoke runs never "
                                                "collide with campaign tags and trigger the skip rule")
    p.add_argument("--time", default="12:00:00", help="walltime per job; must cover ALL arms of a job")
    p.add_argument("--mem", default="8G", help="cluster cap is 8G per job")
    p.add_argument("--cpus", type=int, default=4, help="cluster cap is 4 per job")
    p.add_argument("--env", default="refer-or-clear", help="conda env name or absolute path")
    a = p.parse_args(argv)
    if not re.fullmatch(r"[A-Za-z0-9_.-]+", a.name):
        p.error("--name must contain only letters, digits, dot, underscore, hyphen")
    if a.group_size < 1:
        p.error("--group-size must be at least 1")
    return a


def write_sweep(argv=None) -> list[Path]:
    a = parse_args(argv)
    try:
        arms = expand_arms(_csv(a.protocols), _csv(a.archs), _csv(a.fusions), _csv(a.references),
                           _csv(a.inits), [int(x) for x in _csv(a.seeds)], parse_folds(a.folds))
    except ValueError as e:
        raise SystemExit(f"[make_sweep] {e}")
    out = Path(a.out) if a.out else ROOT / "sweeps" / a.name
    out.mkdir(parents=True, exist_ok=True)
    jobs = pack_jobs(arms, a.group_size)
    paths = []
    for j, job in enumerate(jobs, 1):
        stem = job[0].tag if len(job) == 1 else f"j{j:02d}-{len(job)}arms-{job[0].tag}"
        job_name = f"{a.name}-{job[0].tag}" if len(job) == 1 else f"{a.name}-j{j:02d}"
        path = out / f"{stem}.sh"
        path.write_text(render_job(job, job_name=job_name, time=a.time, mem=a.mem, cpus=a.cpus, env=a.env, suffix=a.suffix,
                                   extra=a.extra))
        path.chmod(path.stat().st_mode | stat.S_IXUSR)
        paths.append(path)
    try:
        rel = out.resolve().relative_to(ROOT)
    except ValueError:
        rel = out
    submit = SUBMIT.format(n=len(paths), name=a.name, out=rel)
    for path in paths:
        target = f"{rel}/{path.name}"
        submit += f'jid=$(sbatch --parsable "{target}") && echo "{target} -> job $jid"\n'
    (out / "submit_all.sh").write_text(submit)
    (out / "submit_all.sh").chmod(0o755)
    print(f"[make_sweep] {len(arms)} arm(s) in {len(paths)} job(s) -> {rel}/  (queue with: bash {rel}/submit_all.sh)")
    return paths


if __name__ == "__main__":
    write_sweep()
