def load(path):
    im = mpimg.imread(path)
    if im.dtype != np.float32 and im.dtype != np.float64:
        im = im.astype(np.float32) / 255.0
    if im.ndim == 2:
        im = np.stack([im] * 3, axis=2)
    if im.shape[2] == 4:
        a = im[:, :, 3:4]
        im = im[:, :, :3] * a + (1.0 - a)
    return np.clip(im[:, :, :3], 0, 1)


def card(name, crop=None, folder=SRC):
    im = load(os.path.join(folder, name))
    if crop is not None:
        y0, y1, x0, x1 = crop
        h, w = im.shape[:2]
        im = im[int(y0 * h):int(y1 * h), int(x0 * w):int(x1 * w)]
    return im


