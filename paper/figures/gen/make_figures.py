# 3. Referral trade-off (illustrative) -----------------------------------------------------------------
# Score model: genuine ~ N(0, 1); altered ~ N(d, 1). With prevalence p and threshold t:
#   R(t) = (1 - p) P(genuine > t) + p P(altered > t);   M(t) = P(altered <= t).
# p = 1 % is one of the paper's assumed prevalence scenarios; at small p the curves barely depend on it.
from math import erf, sqrt


def Phi(x):
    return 0.5 * (1 + erf(x / sqrt(2)))


p = 0.01
ts = np.linspace(-3, 6, 600)
fig, ax = plt.subplots(figsize=(5.6, 3.4))
for d, lab, col in [(1.5, "weak detector (d'=1.5)", "#9c6b4e"), (2.5, "d'=2.5", "#4a6fa5"),
                    (3.5, "strong detector (d'=3.5)", "#2b2b2b")]:
    miss = np.array([Phi(t - d) for t in ts])
    referred = np.array([(1 - p) * (1 - Phi(t)) + p * (1 - Phi(t - d)) for t in ts])
    ax.plot(miss * 100, referred * 100, color=col, lw=1.6, label=lab)
ax.axvline(5, color="#aa4632", lw=0.8, ls=":")
ax.text(5.6, 88, "miss budget 5%", fontsize=7.5, color="#aa4632")
ax.set_xlabel("altered documents missed by the first line (%)")
ax.set_ylabel("documents referred to the second line (%)")
ax.set_xlim(0, 40); ax.set_ylim(0, 100)
ax.grid(alpha=0.25)
ax.legend(loc="center right", fontsize=7.5, frameon=False)
save(fig, "fig_referral")
print("referral done")

